# Shell aliases. Paste into ~/.zshrc or ~/.bashrc.
#
# Run these in a pane or tab other than the one Claude Code occupies.
#   ccl   pick from your recent sessions, every project, origin shown per row
#   ccla  pick from every session ever recorded
#   ccll  pick from one session: the most recently updated, wherever it is

alias ccl='cclinks'
alias ccla='cclinks --all'
alias ccll='cclinks --latest'
